local lu = require("luaunit")
local engine = require("mutate4lua.engine")
local util = require("mutate4lua.util")

local function tmp_dir()
  local base = os.tmpname()
  os.remove(base)
  util.mkdir_p(base)
  return base
end

local function rm_rf(path)
  os.execute("rm -rf " .. string.format("%q", path))
end

local function write_file(path, content)
  local f = assert(io.open(path, "wb"))
  f:write(content)
  f:close()
end

local function report_with(target_rel, hits)
  -- hits is an array where each entry is either a number, "miss", or "blank".
  local lines = {
    "==============================================================================",
    target_rel,
    "==============================================================================",
  }
  for i, kind in ipairs(hits) do
    if kind == "blank" then
      lines[#lines + 1] = "        -- non-executable"
    elseif kind == "miss" then
      lines[#lines + 1] = "  *0    print(" .. tostring(i) .. ")"
    else
      lines[#lines + 1] = string.format("%6d    print(%d)", kind, i)
    end
  end
  lines[#lines + 1] = "=============================================================================="
  lines[#lines + 1] = "other.lua"
  lines[#lines + 1] = "=============================================================================="
  lines[#lines + 1] = "    99    print('other')"
  return table.concat(lines, "\n") .. "\n"
end

TestCoverage = {}

function TestCoverage:setUp()
  self.dir = tmp_dir()
end

function TestCoverage:tearDown()
  rm_rf(self.dir)
end

function TestCoverage:testMarksLinesWithPositiveHitCountAsCovered()
  local path = util.join_path(self.dir, "luacov.report.out")
  write_file(path, report_with("m.lua", {1, "miss", 3, "blank", 5}))
  local covered = engine._parse_luacov_report(path, self.dir, "m.lua")
  lu.assertTrue(covered[1])
  lu.assertNil(covered[2])
  lu.assertTrue(covered[3])
  lu.assertNil(covered[4])
  lu.assertTrue(covered[5])
end

function TestCoverage:testReturnsNilWhenReportFileIsMissing()
  local covered = engine._parse_luacov_report(util.join_path(self.dir, "missing.out"), self.dir, "m.lua")
  lu.assertNil(covered)
end

function TestCoverage:testMatchesTargetByAbsoluteFilenameUnderWorkspaceRoot()
  local path = util.join_path(self.dir, "luacov.report.out")
  write_file(path, report_with(util.join_path(self.dir, "src/m.lua"), {1, 2}))
  local covered = engine._parse_luacov_report(path, self.dir, "src/m.lua")
  lu.assertTrue(covered[1])
  lu.assertTrue(covered[2])
end

function TestCoverage:testIgnoresSectionsForOtherFiles()
  local path = util.join_path(self.dir, "luacov.report.out")
  -- First section is for m.lua (missed), second for other.lua (covered).
  write_file(path, report_with("m.lua", {"miss", "miss"}))
  local covered = engine._parse_luacov_report(path, self.dir, "other.lua")
  lu.assertTrue(covered[1])
end

function TestCoverage:testHandlesReportsWithNonExecutableLinesAndStarZeroMarkers()
  local path = util.join_path(self.dir, "luacov.report.out")
  write_file(path, report_with("m.lua", {"blank", "miss", "blank", 4, "blank"}))
  local covered = engine._parse_luacov_report(path, self.dir, "m.lua")
  lu.assertNil(covered[1])
  lu.assertNil(covered[2])
  lu.assertNil(covered[3])
  lu.assertTrue(covered[4])
  lu.assertNil(covered[5])
end

-- Regression: real luacov reports append a Summary section last; the parser
-- must stop at "Summary" and not leak the coverage-table lines into a bogus
-- file entry.
function TestCoverage:testStopsParsingAtSummarySection()
  local path = util.join_path(self.dir, "luacov.report.out")
  local report = table.concat({
    "==============================================================================",
    "m.lua",
    "==============================================================================",
    " 1 return true",
    "==============================================================================",
    "Summary",
    "==============================================================================",
    "",
    "File   Hits Missed Coverage",
    "---------------------------",
    "m.lua  1    0      100.00%",
    "---------------------------",
    "Total  1    0      100.00%",
  }, "\n")
  write_file(path, report)
  local covered = engine._parse_luacov_report(path, self.dir, "m.lua")
  -- The parser must not treat Summary's coverage-table lines as source
  -- lines for any file: only the genuine m.lua section should contribute.
  lu.assertTrue(covered[1])
  lu.assertNil(covered[2])
end

-- Regression: the parser must handle real luacov 0.17.0 default-reporter
-- output with *0 markers, Summary section, and project-root-relative paths.
function TestCoverage:testParsesRealLuacovReportFixture()
  local report_path = util.join_path(self.dir, "luacov.report.out")
  -- Read the real fixture generated by running lua5.4 -lluacov + luacov
  -- against a small fixture project (tests/fixtures/luacov_real/).
  local real_path = "tests/fixtures/luacov_real/luacov.report.out"
  local real_content = util.read_file(real_path)
  assert(real_content, "real fixture luacov.report.out must exist at " .. real_path)
  write_file(report_path, real_content)

  -- Use the fixture's src/ directory as workspace root so absolute-path
  -- normalization produces the same relative forms as the report.
  local fixture_root = util.absolute_path("tests/fixtures/luacov_real")
  local covered = engine._parse_luacov_report(report_path, fixture_root, "src/calc.lua")

  -- src/calc.lua has 22 source lines; executable lines (with hit count or *0)
  -- are: 1,3,4,7,8,11,12,15,16,17(*0),19,22.  Non-executable (end, blank): rest.
  lu.assertTrue(covered[4], "line 4 (return a + b) is covered")
  lu.assertNil(covered[5], "line 5 (end) is non-executable")
  lu.assertTrue(covered[7], "line 7 (function calc.sub) is covered")
  -- line 17 is *0 (uncovered executable — the zero-check branch never taken)
  lu.assertNil(covered[17], "line 17 (*0: return nil in zero-check) is not covered")
  lu.assertTrue(covered[19], "line 19 (return a / b) is covered")
  lu.assertTrue(covered[22], "line 22 (return calc) is covered")
end

return TestCoverage
